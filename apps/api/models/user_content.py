"""User-owned content blocks: theory links and task files.

These rows are created by the learner themselves (not generated by an agent), so
they live outside ``generated_assets`` and ``topic_resources``. A task can be
scoped to a course, to a learning goal, or both — this lets a learner upload
assignments directly inside a goal's "Задания" tab even when the goal has no
course attached.
"""

import uuid
from datetime import datetime
from typing import Optional

from sqlalchemy import (
    DateTime,
    ForeignKey,
    Integer,
    String,
    Text,
    Boolean,
    func,
    Index,
)
from models.compat import CompatJSONB, CompatUUID
from sqlalchemy.orm import Mapped, mapped_column

from database import Base


class UserTheoryLink(Base):
    """A documentation / theory URL the learner pinned to a course."""

    __tablename__ = "user_theory_links"
    __table_args__ = (
        Index("ix_user_theory_link_user_course", "user_id", "course_id"),
    )

    id: Mapped[uuid.UUID] = mapped_column(CompatUUID, primary_key=True, default=uuid.uuid4)
    user_id: Mapped[uuid.UUID] = mapped_column(
        CompatUUID, ForeignKey("users.id", ondelete="CASCADE")
    )
    course_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        CompatUUID, ForeignKey("courses.id", ondelete="CASCADE"), nullable=True
    )
    title: Mapped[str] = mapped_column(String(300), nullable=False)
    url: Mapped[str] = mapped_column(String(1000), nullable=False)
    description: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    source_type: Mapped[str] = mapped_column(String(30), server_default="documentation")
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )


class UserTaskFile(Base):
    """A task / assignment file the learner uploaded.

    Scoped to a course and/or a learning goal. When the goal has no course the
    file is still attached to the goal via ``goal_id``.
    """

    __tablename__ = "user_task_files"
    __table_args__ = (
        Index("ix_user_task_file_user_course", "user_id", "course_id"),
        Index("ix_user_task_file_user_goal", "user_id", "goal_id"),
    )

    id: Mapped[uuid.UUID] = mapped_column(CompatUUID, primary_key=True, default=uuid.uuid4)
    user_id: Mapped[uuid.UUID] = mapped_column(
        CompatUUID, ForeignKey("users.id", ondelete="CASCADE")
    )
    course_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        CompatUUID, ForeignKey("courses.id", ondelete="CASCADE"), nullable=True
    )
    goal_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        CompatUUID, ForeignKey("learning_goals.id", ondelete="CASCADE"), nullable=True
    )
    filename: Mapped[str] = mapped_column(String(300), nullable=False)
    file_path: Mapped[str] = mapped_column(String(1000), nullable=False)
    mime_type: Mapped[Optional[str]] = mapped_column(String(100), nullable=True)
    size_bytes: Mapped[Optional[int]] = mapped_column(nullable=True)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )


class UserTaskSubmission(Base):
    """A learner's answer to their own uploaded task, plus the AI grading result.

    Verdict: correct | partial | incorrect. When the verdict is not fully
    correct the LLM also generates a remedial (similar) task for practicing the
    missed concept, stored in ``remedial_task``.
    """

    __tablename__ = "user_task_submissions"
    __table_args__ = (
        Index("ix_user_task_submission_user_task", "user_id", "task_file_id"),
    )

    id: Mapped[uuid.UUID] = mapped_column(CompatUUID, primary_key=True, default=uuid.uuid4)
    user_id: Mapped[uuid.UUID] = mapped_column(
        CompatUUID, ForeignKey("users.id", ondelete="CASCADE")
    )
    course_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        CompatUUID, ForeignKey("courses.id", ondelete="CASCADE"), nullable=True
    )
    goal_id: Mapped[Optional[uuid.UUID]] = mapped_column(
        CompatUUID, ForeignKey("learning_goals.id", ondelete="CASCADE"), nullable=True
    )
    task_file_id: Mapped[uuid.UUID] = mapped_column(
        CompatUUID, ForeignKey("user_task_files.id", ondelete="CASCADE")
    )
    user_answer: Mapped[str] = mapped_column(Text, nullable=False)
    submitted_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    verdict: Mapped[str] = mapped_column(String(20), nullable=False)
    # correct | partial | incorrect
    score: Mapped[int] = mapped_column(Integer, default=0, nullable=False)
    # 0-100
    feedback: Mapped[Optional[str]] = mapped_column(Text, nullable=True)
    error_category: Mapped[Optional[str]] = mapped_column(String(50), nullable=True)
    remedial_task: Mapped[Optional[dict]] = mapped_column(CompatJSONB, nullable=True)
    # {question, correct_answer, explanation}
    block_completed: Mapped[bool] = mapped_column(Boolean, default=False, nullable=False)
    # True when this submission marked the tasks block as completed
